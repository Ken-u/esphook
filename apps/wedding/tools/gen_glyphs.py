#!/usr/bin/env python3
"""Rasterises the big banner letters of the wedding app into firmware/wedding_glyphs.h.

The device font only has 12 and 16 px sizes, so the two banners ("新婚快乐" and "Happy Wedding") are baked
from Source Han Sans SC at 28 and 24 px as 2-bit coverage bitmaps (4 levels of anti-aliasing, about 1.5 KB in all).
Needs Pillow and the font that the device fonts were made from, for example the one in LVGL's source tree:

    python3 apps/wedding/tools/gen_glyphs.py --font .../scripts/built_in_font/SourceHanSansSC-Normal.otf

Re-run only when the wording or sizes below change; the generated header is committed.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont

# (set name, size in px, characters). Each distinct character becomes one glyph of that set.
SETS = (("CJK", 28, "新婚快乐"), ("LATIN", 24, "HapyWeding"))
LEVELS = (0, 56, 120, 196)  # coverage thresholds mapping 0..255 to 0..3


def render(font, ch, size):
    """Returns (w, h, left, top, advance, coverage 0..3 rows); top is measured from the baseline (negative = above)."""
    ascent, descent = font.getmetrics()
    cell = size * 3
    image = Image.new("L", (cell, cell), 0)
    draw = ImageDraw.Draw(image)
    origin_x, origin_y = size // 2, size * 2
    draw.text((origin_x, origin_y), ch, font=font, fill=255, anchor="ls")
    bold = Image.new("L", image.size, 0)
    bold.paste(image, (1, 0))  # one pixel of extra weight to the right: the Normal weight is thin at banner size
    image = ImageChops.lighter(image, bold)
    box = image.getbbox()
    advance = round(font.getlength(ch)) + 1
    if box is None:
        return 0, 0, 0, 0, advance, []
    x0, y0, x1, y1 = box
    rows = []
    for y in range(y0, y1):
        row = []
        for x in range(x0, x1):
            v = image.getpixel((x, y))
            row.append(sum(v >= t for t in LEVELS[1:]))
        rows.append(row)
    return x1 - x0, y1 - y0, x0 - origin_x, y0 - origin_y, advance, rows


def pack(rows):
    bits = [v for row in rows for v in row]
    out = bytearray()
    for i in range(0, len(bits), 4):
        chunk = bits[i:i + 4] + [0] * (4 - len(bits[i:i + 4]))
        out.append(chunk[0] << 6 | chunk[1] << 4 | chunk[2] << 2 | chunk[3])
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--font", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "firmware/wedding_glyphs.h")
    parser.add_argument("--preview", action="store_true", help="print the glyphs as ASCII art")
    args = parser.parse_args()
    lines = [
        "#pragma once",
        "/* Generated by apps/wedding/tools/gen_glyphs.py from Source Han Sans SC (SIL OFL); do not edit by hand. */",
        "#include <stdint.h>",
        "/* A glyph is `w` x `h` coverage levels 0..3, packed four to a byte (first pixel in the top bits, row after row).",
        " * `left` and `top` place its box relative to the pen position on the baseline; `advance` moves the pen. */",
        "typedef struct { uint8_t w, h; int8_t left, top; uint8_t advance; uint16_t offset; uint32_t codepoint; } wedding_glyph_t;",
    ]
    blob, tables = bytearray(), []
    for name, size, chars in SETS:
        font = ImageFont.truetype(str(args.font), size)
        entries = []
        for ch in chars:
            w, h, left, top, advance, rows = render(font, ch, size)
            if args.preview:
                print(f"{name} {ch} {w}x{h} left={left} top={top} adv={advance}")
                for row in rows:
                    print("".join(" .oO#"[min(v, 4)] if v < 3 else "#" for v in row))
            entries.append((ch, w, h, left, top, advance, len(blob)))
            blob += pack(rows)
        tables.append((name, size, entries))
    lines.append(f"static const uint8_t WEDDING_GLYPH_DATA[{len(blob)}] = {{")
    for i in range(0, len(blob), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in blob[i:i + 16]) + ",")
    lines.append("};")
    for name, size, entries in tables:
        lines.append(f"/* {size} px */")
        lines.append(f"#define WEDDING_{name}_SIZE {size}")
        lines.append(f"#define WEDDING_{name}_COUNT {len(entries)}")
        lines.append(f"static const wedding_glyph_t WEDDING_{name}_GLYPHS[{len(entries)}] = {{")
        for ch, w, h, left, top, advance, offset in entries:
            lines.append(f"    {{{w}, {h}, {left}, {top}, {advance}, {offset}, 0x{ord(ch):04X}}}, /* {ch} */")
        lines.append("};")
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(blob)} bytes of glyph data)")


if __name__ == "__main__":
    main()
